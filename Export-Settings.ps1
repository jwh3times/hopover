Write-Host 'Exporting drive layout and hardware inventory...' -ForegroundColor Cyan

$drives = foreach ($v in (Get-Volume -ErrorAction SilentlyContinue | Where-Object { $_.DriveLetter -and $_.Size -gt 0 } | Sort-Object DriveLetter)) {
    $part = Get-Partition -DriveLetter $v.DriveLetter -ErrorAction SilentlyContinue
    $disk = if ($part) { Get-Disk -Number $part.DiskNumber -ErrorAction SilentlyContinue } else { $null }
    if (-not $part) {
        # Dynamic (LDM) volumes, e.g. a Windows software mirror, have no basic partition.
        $ldm = @(Get-CimInstance Win32_LogicalDiskToPartition -ErrorAction SilentlyContinue |
            Where-Object { $_.Dependent.DeviceID -eq "$($v.DriveLetter):" } |
            ForEach-Object { if ($_.Antecedent.DeviceID -match 'Disk #(\d+)') { [int]$Matches[1] } } | Sort-Object -Unique)
        if ($ldm.Count) {
            $models = @($ldm | ForEach-Object { (Get-CimInstance Win32_DiskDrive -Filter "Index=$_" -ErrorAction SilentlyContinue).Model } | Sort-Object -Unique)
            $disk = [pscustomobject]@{ FriendlyName = "Dynamic (LDM) volume on disks $($ldm -join ', '): $($models -join ', ')"; BusType = 'dynamic' }
        }
    }
    $top  = @(Get-ChildItem -LiteralPath "$($v.DriveLetter):\" -Force -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -notmatch '^(\$|System Volume Information|pagefile|swapfile|hiberfil|DumpStack|\.bzvol$)' } | ForEach-Object Name)
    [ordered]@{
        Letter     = [string]$v.DriveLetter
        Label      = $v.FileSystemLabel
        FileSystem = $v.FileSystem
        SizeGB     = [math]::Round($v.Size / 1GB)
        UsedGB     = [math]::Round(($v.Size - $v.SizeRemaining) / 1GB)
        Disk       = $(if ($part) { $part.DiskNumber } else { $null })
        Model      = $(if ($disk) { $disk.FriendlyName } else { '' })
        BusType    = $(if ($disk) { [string]$disk.BusType } else { '' })
        TopLevel   = $top
    }
}
$drives = @($drives)
$md  = "# Drive layout$NL$NL"
$md += "Give the new partitions the same letters and labels so paths in app settings keep working. ``Restore.ps1 -Steps drive-letters`` (elevated) reassigns letters by matching labels.$NL$NL"
$md += "| Letter | Label | FS | Size GB | Used GB | Disk | Model | Bus |$NL| --- | --- | --- | --- | --- | --- | --- | --- |$NL"
foreach ($d in $drives) { $md += "| $($d.Letter): | $(Escape-Md $d.Label) | $($d.FileSystem) | $($d.SizeGB) | $($d.UsedGB) | $($d.Disk) | $(Escape-Md $d.Model) | $($d.BusType) |$NL" }
$md += "${NL}USB-bus drives are external: unplug them before installing Windows so the installer can't touch them.$NL"
$md += "${NL}Dynamic (LDM) volumes are Windows software RAID. To keep one, leave its disks alone during setup and use Disk Management > Import Foreign Disks afterwards. To reuse the disks, delete the volume and convert them back to basic.$NL"
foreach ($d in $drives) {
    $md += "$NL## $($d.Letter): $(Escape-Md $d.Label)$NL$NL"
    $md += $(if ($d.TopLevel.Count) { ($d.TopLevel | ForEach-Object { "``$_``" }) -join ', ' } else { '_empty_' }) + $NL
}
Write-Out 'windows\drives.md' $md
Write-Out 'windows\drives.json' (ConvertTo-Json -InputObject $drives -Depth 4)
Add-Note 'Windows' 'windows\drives.md' "$($drives.Count) volumes"

