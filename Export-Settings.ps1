<#
    Export-Settings.ps1
    Exports the settings and lists a fresh Windows install would otherwise lose:
    PATH, environment variables, dev tool config, package-manager lists, VS Code,
    Windows Terminal, Claude Code and Codex config, startup apps, scheduled tasks,
    and a report of work under the dev root that isn't safely in git.

    Secrets are never written: environment variables with secret-looking names or
    values are listed by name only, known secret keys and token shapes in copied
    files are replaced with <redacted>, and a final scan deletes any output file
    that still contains a known secret value.

    Usage (from PowerShell):
        powershell -ExecutionPolicy Bypass -File .\Export-Settings.ps1

    Output:
        <data>\settings\  (override with -OutDir). The folder is rebuilt on
        every run; start with settings\README.md. dev root, repo depth and
        use-only repos come from the Options; parameters override them.

    Skipped on purpose (credentials; sign in again on the new PC):
        ~\.claude\.credentials.json, ~\.codex\auth.json, ~\.codex\secrets,
        ~\.ssh private keys, browser profiles, Windows Credential Manager.
#>

[CmdletBinding(PositionalBinding = $false)]
param(
    # Data folder (default: $env:HOPOVER_DATA, else .\data).
    [string]$DataDir,

    # Defaults to <data>\settings.
    [string]$OutDir,

    # Root folder of your git checkouts, scanned for unpushed or untracked work (default: config devRoot).
    [string]$DevRoot,

    # How many folder levels below each DevRoot folder to look for repos (default: config repoDepth).
    [int]$RepoDepth,

    # Repos (relative to DevRoot) you only use, not develop. Their uncommitted
    # changes and local commits aren't flagged; they still get a clone command.
    # Default: config useOnlyRepos.
    [string[]]$UseOnlyRepos
)

$ErrorActionPreference = 'Continue'

# Windows PowerShell 5.1 leaves $PSScriptRoot empty inside param() defaults.
$scriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
. (Join-Path $scriptDir 'lib\Common.ps1')
$DataDir = Resolve-DataDir $DataDir
$Config  = Get-Options $DataDir
if (-not $DevRoot) { $DevRoot = Expand-ConfigPath $Config.devRoot }
if (-not $PSBoundParameters.ContainsKey('RepoDepth')) { $RepoDepth = [int]$Config.repoDepth }
if (-not $PSBoundParameters.ContainsKey('UseOnlyRepos')) { $UseOnlyRepos = @($Config.useOnlyRepos) }
$UseOnlyRepos = Split-List $UseOnlyRepos

if (-not $OutDir) { $OutDir = Join-Path $DataDir 'settings' }
$OutDir = [IO.Path]::GetFullPath($OutDir)

$H      = $env:USERPROFILE
$Marker = 'Generated by Export-Settings.ps1'
$NL     = "`r`n"

# ---------------------------------------------------------------------------
# Output folder: rebuilt each run, but only if this script created it.
# ---------------------------------------------------------------------------
if (Test-Path -LiteralPath $OutDir) {
    $readme = Join-Path $OutDir 'README.md'
    $ours   = (Test-Path -LiteralPath $readme) -and
              [bool]((Get-Content -LiteralPath $readme -TotalCount 5) -match [regex]::Escape($Marker))
    $empty  = -not (Get-ChildItem -LiteralPath $OutDir -Force | Select-Object -First 1)
    if (-not ($ours -or $empty)) {
        throw "OutDir '$OutDir' exists and was not created by this script; refusing to overwrite it."
    }
    # Keep the last Docker listing in case Docker isn't running this time.
    $prevDockerFile = Join-Path $OutDir 'dev\wsl-docker.md'
    $prevDocker = if (Test-Path -LiteralPath $prevDockerFile) { [IO.File]::ReadAllText($prevDockerFile) } else { '' }
    $prevDockerTime = if ($prevDocker) { (Get-Item -LiteralPath $prevDockerFile).LastWriteTime } else { $null }
    Remove-Item -LiteralPath $OutDir -Recurse -Force
}
New-Item -ItemType Directory -Path $OutDir -Force | Out-Null

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
$script:Secrets    = New-Object 'System.Collections.Generic.HashSet[string]'
$script:RedactHits = 0
$script:Manifest   = New-Object System.Collections.Generic.List[object]
$script:SecretEnv  = New-Object System.Collections.Generic.List[string]

# Key names whose values are treated as secrets.
$SecretKey = '(?:password|passwd|secret|token|api[_-]?key|apikey|access[_-]?key|private[_-]?key|client[_-]?secret|connection[_-]?string|authorization|cookie|credential)'

function Add-Secret([string]$Value) {
    # Short values would cause false positives in the final leak scan.
    if ($Value -and $Value.Length -ge 8 -and $Value -ne '<redacted>') { [void]$script:Secrets.Add($Value) }
}

function Test-SecretName([string]$Name) {
    return ($Name -match "(?i)$SecretKey") -or ($Name -match '(?i)(^|_)(KEY|PAT|PASS|PWD)$')
}

function Test-SecretValue([string]$Value) {
    # Long, unbroken, mixed letters+digits, and not a path or URL: probably a token.
    return $Value.Length -ge 24 -and
           $Value -notmatch '[\\/\s;:]' -and
           $Value -match '^[A-Za-z0-9_\-\.=+]+$' -and
           $Value -match '\d' -and $Value -match '[A-Za-z]'
}

function Protect-Text([string]$Text) {
    if ([string]::IsNullOrEmpty($Text)) { return $Text }

    $keyValue = {
        param($m)
        $v = $m.Groups['v'].Value
        # Leave references such as ${env:X}, $X, %X% and <placeholder> alone.
        if ($v -match '^(\$|%|<)') { return $m.Value }
        Add-Secret $v
        $script:RedactHits++
        return $m.Groups['pre'].Value + '<redacted>' + $m.Groups['post'].Value
    }

    # JSON:  "...password...": "value"
    $Text = [regex]::Replace($Text, "(?i)(?<pre>""[^""\r\n]*$SecretKey[^""\r\n]*""\s*:\s*"")(?<v>[^""\r\n]+)(?<post>"")", $keyValue)
    # TOML / INI quoted:  key = "value"
    $Text = [regex]::Replace($Text, "(?im)(?<pre>^\s*[^\s#;=""]*$SecretKey[^\s=]*\s*=\s*"")(?<v>[^""\r\n]+)(?<post>"")", $keyValue)
    # INI unquoted:  key=value   (e.g. .npmrc  //registry.npmjs.org/:_authToken=...)
    $Text = [regex]::Replace($Text, "(?im)(?<pre>^\s*[^\s#;=""]*$SecretKey[^\s=]*\s*=\s*)(?<v>[^""'\s][^\r\n]*?)(?<post>\s*)$", $keyValue)
    # Credentials embedded in URLs:  https://user:secret@host
    $Text = [regex]::Replace($Text, '(?i)(?<pre>\b[a-z][a-z0-9+.\-]*://[^/\s:@"'']+:)(?<v>[^/\s@"'']+)(?<post>@)', $keyValue)

    # Well-known token shapes, wherever they appear.
    $shape = { param($m) Add-Secret $m.Value; $script:RedactHits++; '<redacted>' }
    $shapes = @(
        'gh[pousr]_[A-Za-z0-9]{20,}',
        'github_pat_[A-Za-z0-9_]{20,}',
        'sk-[A-Za-z0-9_\-]{20,}',
        'xox[abprs]-[A-Za-z0-9\-]{10,}',
        'AKIA[0-9A-Z]{16}',
        'ops_[A-Za-z0-9_\-\.]{20,}',
        'npm_[A-Za-z0-9]{30,}',
        'glpat-[A-Za-z0-9_\-]{20,}',
        'eyJ[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}'
    )
    # The lookbehind stops matches inside longer words (e.g. "Task-S-1-5-21..." is not "sk-...").
    foreach ($p in $shapes) { $Text = [regex]::Replace($Text, '(?<![A-Za-z0-9_])' + $p, $shape) }

    $Text = [regex]::Replace($Text, '(?s)-----BEGIN [A-Z ]*PRIVATE KEY-----.*?-----END [A-Z ]*PRIVATE KEY-----',
        { param($m) $script:RedactHits++; '<redacted private key>' })
    return $Text
}

function Add-Note([string]$Section, [string]$Item, [string]$Status) {
    $script:Manifest.Add([pscustomobject]@{ Section = $Section; Item = $Item; Status = $Status })
}

# Every file this script writes goes through here, so everything is redacted.
function Write-Out([string]$Rel, [string]$Content) {
    $path = Join-Path $OutDir $Rel
    $dir  = Split-Path -Parent $path
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [IO.File]::WriteAllText($path, (Protect-Text $Content), $Utf8)
}

function Copy-Protected([string]$Src, [string]$Rel, [string]$Section, [switch]$Optional) {
    if (-not (Test-Path -LiteralPath $Src -PathType Leaf)) {
        if (-not $Optional) { Add-Note $Section $Rel 'not found' }
        return
    }
    $before = $script:RedactHits
    Write-Out $Rel ([IO.File]::ReadAllText($Src))
    $n = $script:RedactHits - $before
    Add-Note $Section $Rel $(if ($n) { "copied; $n value(s) redacted" } else { 'copied' })
}

function Copy-ProtectedDir([string]$SrcDir, [string]$Rel, [string]$Section, [switch]$Optional) {
    if (-not (Test-Path -LiteralPath $SrcDir -PathType Container)) {
        if (-not $Optional) { Add-Note $Section $Rel 'not found' }
        return
    }
    $root   = $SrcDir.TrimEnd('\')
    $before = $script:RedactHits
    $count  = 0
    Get-ChildItem -LiteralPath $root -Recurse -File -Force -ErrorAction SilentlyContinue |
        Where-Object { $_.Length -le 1MB } |
        ForEach-Object {
            Write-Out (Join-Path $Rel $_.FullName.Substring($root.Length + 1)) ([IO.File]::ReadAllText($_.FullName))
            $count++
        }
    if ($count -eq 0) { if (-not $Optional) { Add-Note $Section $Rel 'empty' }; return }
    $n = $script:RedactHits - $before
    Add-Note $Section "$Rel\ ($count files)" $(if ($n) { "copied; $n value(s) redacted" } else { 'copied' })
}

function Test-Tool([string]$Name) { return [bool](Get-Command $Name -ErrorAction SilentlyContinue) }

function Escape-Md([string]$Text) {
    if ($null -eq $Text) { return '' }
    return ($Text -replace '\|', '\|' -replace '[\r\n]+', ' ').Trim()
}

# Parses JSON whose keys differ only by case (ConvertFrom-Json rejects those).
function ConvertFrom-JsonLoose([string]$Json) {
    if ($PSVersionTable.PSVersion.Major -ge 6) { return ($Json | ConvertFrom-Json -AsHashtable) }
    Add-Type -AssemblyName System.Web.Extensions
    $ser = New-Object System.Web.Script.Serialization.JavaScriptSerializer
    $ser.MaxJsonLength  = [int]::MaxValue
    $ser.RecursionLimit = 1024
    return $ser.DeserializeObject($Json)
}

