Write-Host 'Exporting PATH and environment variables...' -ForegroundColor Cyan

foreach ($scope in 'User', 'Machine') {
    $entries = @(([Environment]::GetEnvironmentVariable('Path', $scope)) -split ';' | Where-Object { $_ })
    Write-Out "windows\path-$($scope.ToLower()).txt" (($entries -join $NL) + $NL)
    Add-Note 'Windows' "windows\path-$($scope.ToLower()).txt" "$($entries.Count) entries"
}

$skipEnv = @{
    User    = '^(Path|TEMP|TMP|OneDrive.*)$'
    Machine = '^(Path|TEMP|TMP|OS|USERNAME|windir|ComSpec|PATHEXT|PSModulePath|NUMBER_OF_PROCESSORS|PROCESSOR_.*|DriverData)$'
}
foreach ($scope in 'User', 'Machine') {
    $vars    = [Environment]::GetEnvironmentVariables($scope)
    $rows    = New-Object System.Text.StringBuilder
    $restore = New-Object System.Text.StringBuilder
    $secretN = 0
    $plain   = [ordered]@{}
    $secretNames = @()
    foreach ($name in ($vars.Keys | Sort-Object)) {
        if ($name -match $skipEnv[$scope]) { continue }
        $val = [string]$vars[$name]
        if ((Test-SecretName $name) -or (Test-SecretValue $val)) {
            Add-Secret $val
            $script:SecretEnv.Add("$name ($scope)")
            $secretN++
            $secretNames += $name
            [void]$rows.AppendLine("| $name | _secret: value withheld, keep it in your password manager_ |")
        } else {
            $plain[$name] = $val
            [void]$rows.AppendLine("| $name | ``$(Escape-Md $val)`` |")
            [void]$restore.AppendLine("[Environment]::SetEnvironmentVariable('$name', '$($val -replace "'", "''")', '$scope')")
        }
    }
    $md  = "# $scope environment variables$NL$NL"
    $md += "PATH is in path-$($scope.ToLower()).txt. Secret values are withheld; set them from your password manager.$NL$NL"
    $md += "| Name | Value |$NL| --- | --- |$NL" + $rows.ToString() + $NL
    $md += "## Restore the non-secret ones$NL$NL"
    if ($scope -eq 'Machine') { $md += "Run from an elevated PowerShell.$NL$NL" }
    $md += '```powershell' + $NL + $restore.ToString() + '```' + $NL
    Write-Out "windows\env-$($scope.ToLower()).md" $md
    # Machine-readable copy for Restore.ps1.
    Write-Out "windows\env-$($scope.ToLower()).json" (([ordered]@{ Variables = $plain; SecretNames = @($secretNames) }) | ConvertTo-Json -Depth 4)
    Add-Note 'Windows' "windows\env-$($scope.ToLower()).md" "$($vars.Count) vars; $secretN secret value(s) withheld"
}

Copy-Protected "$env:windir\System32\drivers\etc\hosts" 'windows\hosts' 'Windows'

Write-Host 'Exporting startup apps and scheduled tasks...' -ForegroundColor Cyan

$startup = New-Object System.Collections.Generic.List[object]
$runKeys = @(
    @{ Scope = 'User';             Path = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run' },
    @{ Scope = 'Machine';          Path = 'HKLM:\Software\Microsoft\Windows\CurrentVersion\Run' },
    @{ Scope = 'Machine (32-bit)'; Path = 'HKLM:\Software\WOW6432Node\Microsoft\Windows\CurrentVersion\Run' }
)
foreach ($k in $runKeys) {
    $item = Get-Item -Path $k.Path -ErrorAction SilentlyContinue
    if (-not $item) { continue }
    foreach ($prop in $item.Property) {
        $startup.Add([pscustomobject]@{ Name = $prop.Trim(); Scope = $k.Scope; Command = [string]$item.GetValue($prop) })
    }
}
foreach ($f in @(@{ Scope = 'Startup folder (user)';      Path = [Environment]::GetFolderPath('Startup') },
                 @{ Scope = 'Startup folder (all users)'; Path = [Environment]::GetFolderPath('CommonStartup') })) {
    Get-ChildItem -LiteralPath $f.Path -File -ErrorAction SilentlyContinue | Where-Object { $_.Name -ne 'desktop.ini' } |
        ForEach-Object { $startup.Add([pscustomobject]@{ Name = $_.BaseName; Scope = $f.Scope; Command = $_.Name }) }
}
$md  = "# Startup apps$NL$NL"
$md += "What launches at sign-in. Most apps re-add themselves when reinstalled; use this to spot the ones you set up by hand.$NL$NL"
$md += "| Name | Where | Command |$NL| --- | --- | --- |$NL"
foreach ($s in ($startup | Sort-Object Name)) { $md += "| $(Escape-Md $s.Name) | $($s.Scope) | ``$(Escape-Md $s.Command)`` |$NL" }
Write-Out 'windows\startup-apps.md' $md
Add-Note 'Windows' 'windows\startup-apps.md' "$($startup.Count) entries"

$tasks = @(Get-ScheduledTask -ErrorAction SilentlyContinue | Where-Object { $_.TaskPath -notlike '\Microsoft\*' } | Sort-Object TaskPath, TaskName)
$md  = "# Scheduled tasks (outside \Microsoft\)$NL$NL"
$md += "Mostly created by installers. Recreate only the ones you made yourself.$NL$NL"
$md += "| Task | State | Author | Action |$NL| --- | --- | --- | --- |$NL"
foreach ($t in $tasks) {
    $act = ($t.Actions | ForEach-Object { ("$($_.Execute) $($_.Arguments)").Trim() } | Where-Object { $_ }) -join '; '
    $md += "| $(Escape-Md ($t.TaskPath + $t.TaskName)) | $($t.State) | $(Escape-Md $t.Author) | ``$(Escape-Md $act)`` |$NL"
}
Write-Out 'windows\scheduled-tasks.md' $md
Add-Note 'Windows' 'windows\scheduled-tasks.md' "$($tasks.Count) tasks"

